import { expect, test } from '@playwright/test';
import { agent, bill, vendor } from './api';

test('Ramp OAuth stages funding selection, confirms replacement, and maps a specific payee', async ({ page }) => {
  const vendorId = await vendor('Ramp mapping vendor');
  await page.goto('/settings/bank');
  await page.getByLabel('Mercury API token').fill('merc-good');
  await page.getByRole('checkbox', { name: 'Sandbox account' }).first().check();
  await page.getByRole('button', { name: 'Connect Mercury' }).click();
  await page.getByRole('combobox', { name: 'Pay bills from' }).click();
  await page.getByRole('option', { name: 'Mercury Payroll ••7781' }).click();
  await page.getByRole('button', { name: 'Connect Mercury' }).click();
  await expect(page.getByRole('definition').filter({ hasText: 'Mercury Payroll' })).toBeVisible();

  // Intercept the consent navigation, not the application or command API.
  // The browser returns exactly the state generated by the real server.
  let returnedState = '';
  await page.route('https://demo.ramp.com/v1/authorize?**', async route => {
    const url = new URL(route.request().url());
    expect(url.searchParams.get('scope')).not.toContain(':write');
    returnedState = url.searchParams.get('state')!;
    const callback = new URL(url.searchParams.get('redirect_uri')!);
    callback.searchParams.set('code', 'fake-code');
    callback.searchParams.set('state', returnedState);
    await route.fulfill({ status: 302, headers: { location: callback.toString() } });
  });
  await page.getByRole('button', { name: 'Authorize Ramp', exact: true }).click();
  await expect(page.getByText('Ramp Test Company · sandbox')).toBeVisible();
  await expect(page).toHaveURL('/settings/bank');
  await expect(page.getByRole('definition').filter({ hasText: 'Mercury Payroll' })).toBeVisible();
  await page.getByRole('combobox', { name: 'Ramp entity and funding account' }).click();
  await page.getByRole('option', { name: 'US Operations · Operating …0042' }).click();
  await page.getByRole('button', { name: 'Review Ramp activation' }).click();
  const dialog = page.getByRole('alertdialog');
  await expect(dialog).toContainText('Replaces mercury: Mercury Payroll');
  await expect(dialog).toContainText('sending and auto-pay remain disabled');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/ramp-activation-mobile.png', fullPage: true });
  await dialog.getByRole('button', { name: 'Select Ramp', exact: true }).click();
  await expect(page.getByText('Disabled — setup only', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Disabled — setup only', { exact: true })).toBeVisible();
  // State can't be replayed after completion.
  const replay = await page.request.post('/api/commands/bank.complete_authorization', {
    headers: { 'x-payvy-client': 'web' }, data: { mode: 'commit', input: { code: 'fake-code', state: returnedState } },
  });
  expect(replay.status()).toBe(409);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(`/vendors/${vendorId}`);
  await page.getByLabel('Search Ramp vendors').fill('Ramp');
  await page.getByRole('button', { name: 'Search Ramp', exact: true }).click();
  await page.getByRole('combobox', { name: 'Vendor in Ramp' }).click();
  await page.getByRole('option', { name: 'Ramp Supplier', exact: true }).click();
  await page.getByRole('combobox', { name: 'Ramp ACH account' }).click();
  await page.getByRole('option', { name: /5678/ }).click();
  await page.getByRole('button', { name: 'Propose Ramp payee' }).click();
  await expect(page.getByText('Proposed. Review it in Waiting on you.')).toBeVisible();
  const detail = await agent<{ payees: { id: string; destination: string; instrument_id: string }[] }>('vendor.get', { vendor_id: vendorId });
  expect(detail.payees[0]!.destination).toBe('…5678');
  expect(detail.payees[0]!.instrument_id).toBe('00000000-0000-4000-8000-000000000002');
  await expect(agent('vendor.accept_payee', { proposal_id: detail.payees[0]!.id })).rejects.toThrow(/403|person/);
  await page.getByRole('link', { name: 'Review in Waiting on you' }).click();
  const card = page.locator('div').filter({ has: page.getByText('Ramp mapping vendor', { exact: true }) })
    .filter({ has: page.getByRole('button', { name: 'Accept', exact: true }) }).last();
  await card.getByRole('button', { name: 'Accept', exact: true }).click();
  await page.goto(`/vendors/${vendorId}`);
  await expect(page.getByText('Accepted by', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/ramp-payee-mobile.png', fullPage: true });
  // Setup must not trap an otherwise-ready bill or silently send it.
  const billId = await bill({ vendor_id: vendorId, invoice_number: 'RAMP-SETUP-1', invoice_date: '2026-11-10', amount_cents: 1000 });
  await page.goto(`/bills/${billId}`);
  await page.getByRole('button', { name: 'Pay…' }).click();
  const release = page.getByRole('dialog');
  await expect(release.getByText('Ramp payments are not enabled yet')).toBeVisible();
  await release.getByRole('button', { name: 'Pay it another way' }).click();
  await expect(release.getByText(/Payvy won't send this payment/)).toBeVisible();
  await release.getByRole('button', { name: 'Release', exact: true }).click();
  await expect(page.getByText('Released', { exact: true })).toBeVisible();
  const mapping = await agent<{ connection_id: string; destinations: { recipient_id: string; instrument_id: string; fingerprint: string }[] }>('bank.recipients', { recipient_id: '00000000-0000-4000-8000-000000000001' });
  await agent('vendor.propose_payee', { vendor_id: vendorId, connection_id: mapping.connection_id, recipient_id: mapping.destinations[0]!.recipient_id,
    method: 'ach', instrument_id: mapping.destinations[0]!.instrument_id, instrument_fingerprint: mapping.destinations[0]!.fingerprint });
  const res = await page.request.post('/api/commands/bank.disconnect', { headers: { 'x-payvy-client': 'web' }, data: { mode: 'commit', input: { provider: 'ramp' } } });
  expect(res.ok()).toBeTruthy();
  await page.goto(`/vendors/${vendorId}`);
  await expect(page.getByText('This payee belongs to a previous bank connection')).toBeVisible();
  await page.goto('/');
  const stale = page.locator('div').filter({ has: page.getByText('Ramp mapping vendor', { exact: true }) })
    .filter({ has: page.getByRole('button', { name: 'Accept', exact: true }) }).last();
  await expect(stale.getByRole('button', { name: 'Accept', exact: true })).toBeDisabled();
  await expect(stale.getByText('This proposal is for a previous bank connection')).toBeVisible();

});

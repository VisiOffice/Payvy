// Generates src/api/commands.gen.ts from src/api/commands.json, which is
// `payvy commands`: every command's name, tier and input JSON Schema. Run
// `pnpm gen:api` after changing a command; CI checks the output is current.
import { readFileSync, writeFileSync } from 'node:fs';
import { compile } from 'json-schema-to-typescript';

const here = new URL('../src/api/', import.meta.url);
const { commands } = JSON.parse(readFileSync(new URL('commands.json', here), 'utf8'));

const typeName = (name) =>
  name.split(/[._]/).map((p) => p[0].toUpperCase() + p.slice(1)).join('') + 'Input';

let out = `// Generated by scripts/gen-api.mjs from \`payvy commands\`. Don't edit.\n\n`;
for (const c of commands) {
  const schema = { ...JSON.parse(c.input_schema), additionalProperties: false };
  out += await compile(schema, typeName(c.name), {
    bannerComment: '',
    additionalProperties: false,
    format: true,
    strictIndexSignatures: true,
  });
  out += '\n';
}
out += `export interface CommandInputs {\n`;
for (const c of commands) out += `  ${JSON.stringify(c.name)}: ${typeName(c.name)};\n`;
out += `}\n\nexport type CommandName = keyof CommandInputs;\n\n`;
out += `export type Tier = 'read' | 'routine' | 'confirmed';\n\n`;
out += `export const COMMANDS: Record<CommandName, { tier: Tier; personOnly: boolean; summary: string }> = {\n`;
for (const c of commands) {
  out += `  ${JSON.stringify(c.name)}: { tier: ${JSON.stringify(c.tier)}, personOnly: ${c.person_only}, summary: ${JSON.stringify(c.summary)} },\n`;
}
out += `};\n`;
writeFileSync(new URL('commands.gen.ts', here), out);
console.log(`wrote ${commands.length} commands`);
